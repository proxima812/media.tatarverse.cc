/**
 * Приведение текста к виду, по которому сравнивается поиск каталога.
 *
 * Каталог трехъязычный по названиям: рядом стоят «Журнал «Ағиҙел»»,
 * «Balaçıqlar İçün Resimli Luğat» и «Ana tele». Человек набирает их без
 * диакритики и без башкирских букв - «агидел», «balaciqlar», - поэтому
 * перед сравнением обе стороны складываются к базовым буквам.
 *
 * Один модуль на две стороны: строка записи собирается на сборке
 * (`CatalogGlossary.astro`), запрос - в браузере. Разъедься эти правила,
 * и часть каталога стала бы ненаходимой.
 */

/**
 * Буквы, которые Unicode не считает вариантами базовых: `NFD` их не
 * разбирает, потому что это самостоятельные буквы своих алфавитов, а не
 * «буква + знак». Для поиска они все равно взаимозаменяемы с базовыми.
 */
const FOLD_MAP: Record<string, string> = {
	ә: "а",
	ө: "о",
	ү: "у",
	ғ: "г",
	ҙ: "з",
	ҡ: "к",
	ң: "н",
	ҫ: "с",
	һ: "х",
	і: "и",
	ї: "и",
	ґ: "г",
	ў: "у",
	е: "е",
	ı: "i",
	ø: "o",
	đ: "d",
	ł: "l",
	ß: "ss",
};

/**
 * Второе чтение тех же башкирских и татарских букв. У них нет одного
 * «правильного» русского соответствия: ҙ звучит как [ð] и складывается в
 * з, но в русских названиях пишется через д («Ағиҙел» - «Агидель»), ҫ -
 * то с, то т, ә - то а, то э. Человек наберет любой из вариантов, поэтому
 * в строку записи попадают оба, а запрос сворачивается только основным.
 */
const ALT_FOLD_MAP: Record<string, string> = {
	ҙ: "д",
	ҫ: "т",
	һ: "г",
	ә: "э",
	ө: "е",
	ү: "ю",
	і: "i",
};

/** Диакритические знаки, отделенные нормализацией `NFD`. */
const COMBINING_MARKS = /[̀-ͯ]/g;

function fold(value: string, map: Record<string, string>): string {
	const lowered = value
		.toLowerCase()
		.normalize("NFD")
		.replace(COMBINING_MARKS, "");

	let folded = "";
	for (const char of lowered) folded += map[char] ?? FOLD_MAP[char] ?? char;

	return folded;
}

/** Свертка запроса - и основной вариант строки записи. */
export function foldSearchText(value: string): string {
	return fold(value, FOLD_MAP);
}

/**
 * Строка, по которой ищется запись: обе свертки через пробел. Дубли не
 * мешают - сравнение идет по вхождению подстроки, а лишний вариант только
 * добавляет еще один способ найти ту же карточку.
 */
export function searchHaystack(value: string): string {
	const primary = fold(value, FOLD_MAP);
	const alternate = fold(value, ALT_FOLD_MAP);

	return primary === alternate ? primary : `${primary} ${alternate}`;
}
